KEYWORDS = {s: [(k, int(w)) for k, w in (x.split(":") for x in v.split())] for s, v in _KW.items()}
_FORMULA = re.compile(r"(?<![A-Za-z0-9])(?:(?:[A-Z][a-z]?\d*){2,}|[A-Z][a-z]?\d+|Fe|Cu|Zn|Mg|Al|Na)(?![A-Za-z0-9])")
_UNIT = re.compile(r"\d\s*(?:m/s|km/h|N|J|W|kg|Pa|V|A|Ω|Hz|kW|℃|cm³|g/cm)(?![A-Za-z])")
_EN_WORD = re.compile(r"[A-Za-z]{2,}")
_BLANK = re.compile(r"_{2,}|\(\s*[a-z]+\s*\)")


def canonical(subject):
    """模型 / 会话里的学科名 → 策略表里的键（未知返回空串）。"""
    s = (subject or "").strip()
    if not s:
        return ""
    s = ALIASES.get(s, s)
    if s in STRATEGIES and s != "通用":
        return s
    for k in STRATEGIES:
        if k != "通用" and k in s:
            return k
    for a, k in ALIASES.items():
        if len(a) > 1 and a in s:
            return k
    return ""


def classify(text):
    """关键词打分：返回 (学科, 分数)，没有命中返回 ("", 0)。确定性、可复现。"""
    t = text or ""
    if not t.strip():
        return "", 0
    score = {s: 0 for s in KEYWORDS}
    low = t.lower()
    for s, kws in KEYWORDS.items():
        for k, w in kws:
            if k.lower() in low:
                score[s] += w
    if _FORMULA.search(t) and re.search(r"反应|方程式|配平|生成|=|→|点燃", t):
        score["化学"] += 3
    if _UNIT.search(t):
        score["物理"] += 2
    words = _EN_WORD.findall(t)
    letters = sum(len(w) for w in words)
    cjk = len(re.findall(r"[\u4e00-\u9fff]", t))
    if len(words) >= 3 and letters >= cjk and not re.search(r"[=^]|sin|cos|log", t):
        score["英语"] += 4
    elif len(words) >= 3 and _BLANK.search(t):
        score["英语"] += 3
    best = max(score, key=lambda s: (score[s], -list(KEYWORDS).index(s)))
    if score[best] <= 0:
        return "", 0
    ties = [s for s in score if score[s] == score[best]]
    return (best if len(ties) == 1 else ties[0]), score[best]


def _band_key(subject, band):
    if band == "primary" and subject in PRIMARY_MAP:
        return PRIMARY_MAP[subject]
    return subject


NEW_PROBLEM_MIN = 3   # 关键词分数达到这个值，且文本像一道新题，才会改掉会话里的学科


def route(text="", problem="", session_subject="", band="middle", model_subject=""):
    """决定本轮用哪一科的策略。返回 {subject, label, source, score}。
    优先级：模型字段 > （新题且关键词得分 ≥ 3 时）关键词 > 会话学科 > 关键词（≥1）> 题干关键词 > 通用。"""
    m = canonical(model_subject)
    kw, sc = classify(text)
    sess = canonical(session_subject)
    if m:
        subj, src, score = m, "model", None
    elif kw and sc >= NEW_PROBLEM_MIN and kw != sess and len((text or "").strip()) >= 6:
        subj, src, score = kw, "keyword", sc
    elif sess:
        subj, src, score = sess, "session", None
    elif kw:
        subj, src, score = kw, "keyword", sc
    else:
        pk, ps = classify(problem)
        subj, src, score = (pk, "keyword", ps) if pk else ("通用", "default", 0)
    key = _band_key(subj, band)
    return {"subject": key, "label": label(key, band), "source": src, "score": score}


def label(subject, band):
    st = STRATEGIES.get(subject) or STRATEGIES["通用"]
    return (st.get("bands", {}).get(band) or {}).get("label") or (subject if subject != "通用" else "")


def get(subject, band="middle", text=""):
    """合并学段覆盖与题型细分后的策略（dict 副本）。"""
    key = _band_key(canonical(subject) or "通用", band)
    base = STRATEGIES.get(key) or STRATEGIES["通用"]
    st = {k: v for k, v in base.items() if k not in ("bands", "genres")}
    st["subject"], st["notes"], st["genre"] = key, [], ""
    ov = base.get("bands", {}).get(band) or {}
    for k in ("mode", "levels", "label"):
        if k in ov:
            st[k] = ov[k]
    if ov.get("note"):
        st["notes"].append(ov["note"])
    for g in base.get("genres", []):
        if text and re.search(g["re"], text, re.I):
            st["mode"], st["genre"] = g["mode"], g["name"]
            st["notes"].append(g["note"])
            break
    st.setdefault("label", key if key != "通用" else "")
    return st


def mode_line(subject, band="middle", text=""):
    return get(subject, band, text)["mode"]


def leak_family(subject):
    key = canonical(subject)
    if not key:
        return "math"            # 学科未知：沿用原来的数学规则
    return STRATEGIES[key]["leak"]


def fallback(subject):
    key = canonical(subject) or "通用"
    return STRATEGIES[key]["fallback"]


def prompt_block(subject, band="middle", text=""):
    """注入系统提示词的「本科引导策略」。学科未知时给一张简表，让模型先认学科再按该科规则。"""
    key = _band_key(canonical(subject) or "", band)
    if not key or key == "通用":
        rows = []
        for s in ("数学", "物理", "化学", "英语", "语文", "生物", "历史", "地理", "道德与法治", "科学"):
            k = _band_key(s, band)
            if k != s:
                continue
            rows.append(f"- {label(s, band) or s}：{STRATEGIES[s]['mode']}。不能直接给：{STRATEGIES[s]['never']}")
        out = "学科还没确定：先判断这道题属于哪一科，再按该科的方式引导：\n" + "\n".join(rows)
        if band == "primary":
            out += "\n" + PRIMARY_STYLE
        return out
    st = get(key, band, text)
    lv = st["levels"]
    lines = [f"本题按「{st['label'] or key}」引导（{BAND_NAMES.get(band, '')}{'·' + st['genre'] if st['genre'] else ''}）：{st['mode']}。",
             f"- 第 1 层 · {lv[0]}", f"- 第 2 层 · {lv[1]}", f"- 第 3 层 · {lv[2]}",
             f"- 不能直接给：{st['never']}", f"- 可以直接给：{st['allow']}", f"- 检查学生答案：{st['check']}",
             "- 常见卡点与追问（按学生情况选一个问，不要全问）：" + "；".join(f"{a} → 「{q}」" for a, q in st["stuck"])]
    for n in st["notes"]:
        lines.append(f"- 注意：{n}")
    if band == "primary":
        lines.append("- " + PRIMARY_STYLE)
    return "\n".join(lines)


def public(route_info, band="middle", text=""):
    """给前端 / 会话状态用的精简信息。"""
    subj = route_info.get("subject") or "通用"
    st = get(subj, band, text)
    return {"subject": subj if subj != "通用" else "", "label": st["label"] or "", "mode": st["mode"],
            "genre": st["genre"], "source": route_info.get("source"), "leak": STRATEGIES.get(subj, STRATEGIES["通用"])["leak"]}
